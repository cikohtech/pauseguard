// Generates src/components/icons/{names,rounded,outlined}.ts: the Material Symbols (Apache-2.0, weight 400) this app
// uses, as SVG path data. Rounded for the customer app and the landing page, Outlined for the
// console (as Google Cloud does). Only the icons listed here ship; an unknown name fails `tsc`.
//
//   npm i --prefix /tmp/ms @material-symbols/svg-400@0.48.0   # 94 MB, so not a project dependency
//   node scripts/gen-icons.mjs /tmp/ms/node_modules/@material-symbols/svg-400
//
// A trailing "+" also emits the filled variant (`<Icon name="home" fill />`).
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ICONS = `
  account_balance add_photo_alternate apartment apps arrow_back arrow_forward back_hand+ bar_chart
  bolt call+ category check check_circle+ chevron_right close cloud content_paste credit_card
  dashboard+ database deployed_code description document_search encrypted error+ flag+ format_quote
  forum gavel gpp_bad+ gpp_maybe+ history home+ home_work hub image inbox+ info+ keyboard language
  left_click link local_police lock+ login logout menu mobile mobile_chat monitoring
  network_intelligence notifications_active+ notifications_off open_in_new pause_circle+ payments
  person+ person_add person_search phone_in_talk picture_as_pdf policy+ progress_activity public
  query_stats receipt_long refresh report+ rule savings schedule+ search send shield_lock+
  shield_person+ shopping_bag sms speed+ swap_horiz switch_account+ table task_alt thumb_down+
  thumb_up+ timer translate travel_explore undo verified_user+ warning+ wifi signal_cellular_alt
  battery_full wand_stars edit_note arrow_drop_down
`
  .trim()
  .split(/\s+/)

const root = process.argv[2]
if (!root || !existsSync(join(root, 'rounded'))) {
  console.error('usage: node scripts/gen-icons.mjs <path to @material-symbols/svg-400>')
  process.exit(1)
}

const pathOf = (style, file) => {
  const svg = readFileSync(join(root, style, `${file}.svg`), 'utf8')
  const d = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1])
  if (d.length === 0) throw new Error(`no path in ${style}/${file}.svg`)
  return d.join(' ')
}

const names = ICONS.map((n) => n.replace(/\+$/, ''))
const sets = { rounded: {}, outlined: {} }
for (const raw of ICONS) {
  const name = raw.replace(/\+$/, '')
  for (const style of Object.keys(sets)) {
    sets[style][name] = pathOf(style, name)
    if (raw.endsWith('+')) sets[style][`${name}-fill`] = pathOf(style, `${name}-fill`)
  }
}

const body = (set) =>
  Object.entries(set)
    .map(([k, d]) => `  ${/^[a-z_][a-z0-9_]*$/.test(k) ? k : `'${k}'`}: '${d}',`)
    .join('\n')

const header = `// GENERATED by scripts/gen-icons.mjs from @material-symbols/svg-400 (Apache-2.0). Do not edit.
// viewBox "0 -960 960 960". Keys ending in -fill are the filled variants.
`
const out = (file, text) => writeFileSync(new URL(`../src/components/icons/${file}`, import.meta.url), header + text)
out('names.ts', `\nexport type IconName =\n${names.map((n) => `  | '${n}'`).join('\n')}\n\nexport type IconSet = Record<string, string>\n`)
// one module per style, so the console's Outlined set stays in the console's lazy chunk
out('rounded.ts', `import type { IconSet } from './names'\n\nexport const ROUNDED: IconSet = {\n${body(sets.rounded)}\n}\n`)
out('outlined.ts', `import type { IconSet } from './names'\n\nexport const OUTLINED: IconSet = {\n${body(sets.outlined)}\n}\n`)
console.log(`${names.length} icons, ${Object.keys(sets.rounded).length} paths per style`)
